// Server keys reach a station only with a certificate the client signs
// (docs/ARCHITECTURE.md section 7): for a while (default 7 days, renewed
// when Valise opens), from the server's address, limited to rrsync
// (write only, no deleting or overwriting) or a restricted sftp-server.
// The signing key is kept encrypted to the user's own age key, so signing
// needs the Valise passphrase.

const (
	caName           = "_ca"
	stationCertsFile = "station-certs.json"
	defaultCertHours = 168
	renewBefore      = 48 * time.Hour
)

func (s *Service) caPath() string {
	return filepath.Join(config.StationKeyDir(s.Dirs.Data, ""), caName)
}

// certHours is the configured certificate lifetime.
func (s *Service) certHours() int {
	h := s.Config.StationCertHours
	if h < 1 || h > 720 {
		return defaultCertHours
	}
	return h
}

// ensureCA makes the signing key once: generated by ssh-keygen, its
// private half encrypted with age to the user's recipient, the plaintext
// removed.
func (s *Service) ensureCA(ctx context.Context) (pub string, err error) {
	if b, err := os.ReadFile(s.caPath() + ".pub"); err == nil && fileExists(s.caPath()+".age") {
		return strings.TrimSpace(string(b)), nil
	}
	info, err := s.KeyShow()
	if err != nil {
		return "", valise.New("key_missing", "还没有加密钥匙，无法给空间站签发证书", "先创建加密钥匙：valise key init")
	}
	rcpt, err := age.ParseX25519Recipient(info.Recipient)
	if err != nil {
		return "", err
	}
	tmp, err := s.privateTemp()
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(tmp)
	key := filepath.Join(tmp, caName)
	if err := runTool(ctx, s.toolPath("ssh-keygen"), []string{"-q", "-t", "ed25519", "-N", "", "-C", "valise-ca@" + localName(), "-f", key}, os.Environ()); err != nil {
		return "", valise.New("keygen_failed", "无法生成空间站签发钥匙", "确认本机安装了 OpenSSH 的 ssh-keygen").WithDetail(err.Error())
	}
	plain, err := os.ReadFile(key)
	if err != nil {
		return "", err
	}
	var enc bytes.Buffer
	w, err := age.Encrypt(&enc, rcpt)
	if err != nil {
		return "", err
	}
	w.Write(plain)
	if err := w.Close(); err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(s.caPath()), 0o700); err != nil {
		return "", err
	}
	if err := os.WriteFile(s.caPath()+".age", enc.Bytes(), 0o600); err != nil {
		return "", err
	}
	b, err := os.ReadFile(key + ".pub")
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(s.caPath()+".pub", b, 0o644); err != nil {
		return "", err
	}
	return strings.TrimSpace(string(b)), nil
}

// privateTemp is a 0700 directory under the cache, removed by the caller.
func (s *Service) privateTemp() (string, error) {
	dir := filepath.Join(s.Dirs.Cache, "tmp")
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	return os.MkdirTemp(dir, "sign-")
}

// certOptions is what one certificate allows.
type certOptions struct {
	principal string
	command   string // force-command
	source    string // source-address, "" for any
	valid     time.Duration
}

// signCert signs pub (an OpenSSH public key line) with the signing key,
// decrypted with the owner's identity into a private temporary folder.
func (s *Service) signCert(ctx context.Context, host, id, pub string, o certOptions) (string, error) {
	ident, err := s.ownerIdentity(host)
	if err != nil {
		return "", err
	}
	enc, err := os.ReadFile(s.caPath() + ".age")
	if err != nil {
		return "", valise.New("ca_missing", "找不到空间站签发钥匙", "在这台电脑上重新添加空间站")
	}
	r, err := age.Decrypt(bytes.NewReader(enc), ident)
	if err != nil {
		return "", valise.New("ca_locked", "空间站签发钥匙解不开：它不是用你现在的加密钥匙保护的", "在这台电脑上重新添加空间站").WithDetail(err.Error())
	}
	plain, err := io.ReadAll(r)
	if err != nil {
		return "", err
	}
	tmp, err := s.privateTemp()
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(tmp)
	ca, key := filepath.Join(tmp, caName), filepath.Join(tmp, "station")
	if err := os.WriteFile(ca, plain, 0o600); err != nil {
		return "", err
	}
	if err := os.WriteFile(key+".pub", []byte(pub+"\n"), 0o600); err != nil {
		return "", err
	}
	args := []string{"-q", "-s", ca, "-I", id, "-n", o.principal, "-V", "+" + strconv.Itoa(int(o.valid.Minutes())) + "m", "-O", "clear"}
	if o.command != "" {
		args = append(args, "-O", "force-command="+o.command)
	}
	if o.source != "" {
		args = append(args, "-O", "source-address="+o.source)
	}
	if err := runTool(ctx, s.toolPath("ssh-keygen"), append(args, key+".pub"), os.Environ()); err != nil {
		return "", valise.New("cert_sign_failed", "签发空间站证书失败", "重试；仍不行请报告").WithDetail(err.Error())
	}
	cert, err := os.ReadFile(key + "-cert.pub")
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(cert)), nil
}

// certLimit is the forced command and kind a station allows for server
// keys; ok is false when it offers neither rrsync nor sftp-server.
func certLimit(st config.Station, server string) (command, kind string, rooted, ok bool) {
	switch {
	case st.RRsync:
		return "rrsync -wo -no-del -no-overwrite " + strings.TrimRight(st.Path, "/") + "/" + server, stationsync.MethodRRsync, true, true
	case st.SFTPServer != "":
		return st.SFTPServer + " -P remove,rmdir,posix-rename,setstat,fsetstat,lsetstat,symlink,hardlink", stationsync.MethodSFTP, false, true
	}
	return "", "", false, false
}

// CertState is a server's certificate for a station.
type CertState struct {
	Expires time.Time `json:"expires"`
	Source  string    `json:"source,omitempty"`
}

func (s *Service) loadCerts() map[string]map[string]CertState {
	out := map[string]map[string]CertState{}
	if b, err := os.ReadFile(filepath.Join(s.Dirs.Data, stationCertsFile)); err == nil {
		json.Unmarshal(b, &out)
	}
	return out
}

func (s *Service) recordCert(host, station string, c CertState) {
	all := s.loadCerts()
	if all[host] == nil {
		all[host] = map[string]CertState{}
	}
	all[host][station] = c
	b, _ := json.MarshalIndent(all, "", "  ")
	_ = os.WriteFile(filepath.Join(s.Dirs.Data, stationCertsFile), append(b, '\n'), 0o600)
}

// Cert returns host's certificate state for a station.
func (s *Service) Cert(host, station string) (CertState, bool) {
	c, ok := s.loadCerts()[host][station]
	return c, ok
}

// certFresh reports a certificate that does not need renewing yet.
func (s *Service) certFresh(host, station string) bool {
	c, ok := s.Cert(host, station)
	return ok && time.Until(c.Expires) > renewBefore
}

// issueCert gives host's station key a certificate: a five-minute probe
// first, to learn the address the station sees, then the real one.
func (s *Service) issueCert(ctx context.Context, host, serverName, pub string, st config.Station) error {
	command, _, _, ok := certLimit(st, serverName)
	if !ok {
		return valise.New("station_unlimited", "空间站 "+st.Name+" 没有 rrsync 也没有 sftp-server，无法限制服务器的钥匙", "Valise 不给服务器凭据，改由这台电脑中转")
	}
	id := "valise:" + serverName + ":" + st.Name
	source := ""
	if !st.AnySource {
		probe, err := s.signCert(ctx, host, id+":probe", pub, certOptions{principal: st.User, command: "echo $SSH_CLIENT", valid: 5 * time.Minute})
		if err != nil {
			return err
		}
		if err := s.call(ctx, host, vaultrpc.MethodStationCert, vaultrpc.StationCertParams{Name: st.Name, Cert: probe}, nil); err != nil {
			return err
		}
		var res vaultrpc.StationProbeResult
		if err := s.call(ctx, host, vaultrpc.MethodStationProbe, vaultrpc.StationKeyParams{Name: st.Name}, &res); err != nil {
			return valise.New(stationsync.UnreachableCode, "服务器连不上空间站 "+st.Name, "经这台电脑中转").WithDetail(errText1(err))
		}
		if f := strings.Fields(res.Output); len(f) > 0 && hostRe(f[0]) {
			source = f[0]
		}
	}
	valid := time.Duration(s.certHours()) * time.Hour
	cert, err := s.signCert(ctx, host, id, pub, certOptions{principal: st.User, command: command, source: source, valid: valid})
	if err != nil {
		return err
	}
	if err := s.call(ctx, host, vaultrpc.MethodStationCert, vaultrpc.StationCertParams{Name: st.Name, Cert: cert}, nil); err != nil {
		return err
	}
	s.recordCert(host, st.Name, CertState{Expires: time.Now().Add(valid), Source: source})
	return nil
}

// hostRe accepts an IPv4 or IPv6 address as printed in SSH_CLIENT.
func hostRe(a string) bool {
	return a != "" && len(a) <= 45 && strings.Trim(a, "0123456789abcdefABCDEF.:") == ""
}

// RenewCerts renews host's expiring station certificates while the Valise
// passphrase is unlocked (nothing is asked); renewed names are returned.
func (s *Service) RenewCerts(ctx context.Context, host string) ([]string, error) {
	if _, ok := s.OwnerRemaining(); !ok {
		return nil, nil
	}
	var done []string
	for station := range s.loadCerts()[host] {
		if s.certFresh(host, station) {
			continue
		}
		st, err := s.station(station)
		if err != nil {
			continue
		}
		status, err := s.VaultStatus(ctx, host)
		if err != nil {
			return done, err
		}
		if err := s.attachStation(ctx, host, *st, status); err != nil {
			return done, err
		}
		done = append(done, station)
	}
	return done, nil
}

// ExpiringCerts lists host's station certificates that need renewing.
func (s *Service) ExpiringCerts(host string) []string {
	var out []string
	for station := range s.loadCerts()[host] {
		if !s.certFresh(host, station) {
			out = append(out, station)
		}
	}
	return out
}
